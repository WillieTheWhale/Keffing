#!/usr/bin/env python3
"""The ALLOY background (derived from the CHROME study) — typed ASCII renderings of the site's skies.

Turns sky photographs into fields of mono glyphs (the r01 / r16 dot-matrix
texture): dense glyphs where the sky is dark, paper where the cloud is, so
the clouds read as negative space in a block of type. Writes
components/background/asciiSky.ts.

  python3 scripts/background/make_ascii.py
"""
import os
import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
SKY = os.path.join(ROOT, "public/assets/sky")
OUT = os.path.join(ROOT, "components/background/asciiSky.ts")
RAMP = " .·:;il!|1I[]{}JX#"


def field(src, box, cols, rows, gamma=1.0, cut=0.12):
    im = Image.open(os.path.join(SKY, src)).convert("L")
    if box:
        im = im.crop(box)
    # cells are taller than wide (4.2 x 6.2)
    im = im.resize((cols, rows), Image.LANCZOS).filter(ImageFilter.UnsharpMask(1.2, 80, 2))
    a = np.asarray(im, np.float32) / 255.0
    lo, hi = np.percentile(a, 3), np.percentile(a, 97)
    a = np.clip((a - lo) / max(1e-3, hi - lo), 0, 1)
    d = (1 - a) ** gamma          # dark sky → dense
    d = np.where(d < cut, 0, d)
    rng = np.random.default_rng(7)
    lines = []
    for y in range(rows):
        row = ""
        for x in range(cols):
            v = d[y, x] + rng.normal(0, 0.04)
            i = int(np.clip(v, 0, 0.999) * len(RAMP))
            row += RAMP[i]
        lines.append(row.rstrip())
    return lines


fields = {
    "cumulus": field("sky-7.jpg", (100, 300, 1100, 1300), 58, 36, 1.9, 0.3),
    "eddies": field("sky-18.jpg", (200, 200, 1400, 1100), 64, 30, 1.3, 0.2),
    # the eye of Supertyphoon Yuri (STS-44) — the contact section's open channel
    "eye": field("sky-19.jpg", (300, 250, 1300, 1150), 60, 38, 1.5, 0.22),
}
with open(OUT, "w") as f:
    f.write("// Generated by scripts/background/make_ascii.py — typed renderings of the site's sky photos.\n")
    f.write("export const ASCII_SKY: Record<string, string[]> = {\n")
    for k, lines in fields.items():
        f.write(f"  {k}: [\n")
        for l in lines:
            f.write("    " + repr(l).replace("'", '"') + ",\n" if '"' not in l else "    '" + l + "',\n")
        f.write("  ],\n")
    f.write("};\n")
print("wrote", OUT)
for l in fields["eye"]:
    print(l)
